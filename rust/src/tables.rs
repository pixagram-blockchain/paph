/// 16-bit popcount table, built at compile time (it was rebuilt per compare).
pub fn pop_table() -> &'static [u8] {
    static T: [u8; 65536] = {
        let mut t = [0u8; 65536];
        let mut i = 1;
        while i < 65536 {
            t[i] = t[i >> 1] + (i & 1) as u8;
            i += 1;
        }
        t
    };
    &T
}

#[inline(always)]
pub fn popcnt32(pop: &[u8], x: u32) -> i32 {
    pop[(x & 0xffff) as usize] as i32 + pop[((x >> 16) & 0xffff) as usize] as i32
}

