#[cfg(debug_assertions)]
pub fn check() {
    for k in 0..64usize {
        let m = ((32 - k as i32) & 63) as usize;
        assert_eq!(COS64[m], -COS64[k]);
        assert_eq!(SIN64[m], SIN64[k]);
        assert_eq!(RC10[m], -RC10[k]);
        assert_eq!(RS10[m], RS10[k]);
    }
}
